def _alerts_html(alerts: list[Alert], app_names: dict[str, str], rules: list[Rule]) -> str:
    if not alerts:
        checked = f" ({len(rules)} rule(s) checked)" if rules else ""
        return f'<ul class="alerts"><li class="ok"><span class="sev">OK</span>No active alerts{checked}.</li></ul>'
    items = []
    for a in alerts:
        icon = "✖" if a.severity == "critical" else "▲"
        items.append(
            f'<li class="{a.severity}"><span class="sev">{icon} {a.severity.title()}</span>'
            f"<strong>{escape(app_names.get(a.app_id, a.app_id))}</strong> · <code>{escape(a.rule)}</code> · {a.date}"
            f"<br>{escape(a.message)}</li>"
        )
    return '<ul class="alerts">' + "".join(items) + "</ul>"


def _checks_html(checks: list[CheckResult] | None) -> str:
    if checks is None:
        return '<p class="note">Data-quality checks were not run for this build.</p>'
    if not checks:
        return '<p class="note">No data-quality checks configured (checks.yaml).</p>'
    s = summarize(checks)
    head = (
        f'<p class="note">{s["passed"]} of {s["checks"]} checks passed'
        f" · {s['errors']} error(s) · {s['warnings']} warning(s). "
        "Checks are defined in <code>checks.yaml</code>; errors fail the refresh.</p>"
    )
    bad = [c for c in checks if c.status != "pass"]
    if not bad:
        return (
            head
            + '<ul class="alerts"><li class="ok"><span class="sev">OK</span>All data-quality checks passed.</li></ul>'
        )
    items = []
    for c in bad:
        cls = "critical" if c.severity == "error" else "warning"
        label = "Error" if c.severity == "error" else "Warning"
        if c.status == "error":
            label += " (check could not run)"
        items.append(
            f'<li class="{cls}"><span class="sev">{label}</span>'
            f"<code>{escape(c.name)}</code>"
            + (f" · {escape(c.table)}" if c.table else "")
            + f"<br>{escape(c.message)}</li>"
        )
    return head + '<ul class="alerts">' + "".join(items) + "</ul>"


def _freshness(
    con: duckdb.DuckDBPyConnection, as_of: dt.date, app_id: str | None, names: dict[str, str]
) -> str:
    rows = q(
        con,
        "SELECT * FROM fct_source_freshness"
        + (" WHERE app_id = ?" if app_id else "")
        + " ORDER BY app_id, source",
        [app_id] if app_id else [],
    )
    if not rows:
        return '<p class="note">No loads recorded yet.</p>'
    out = []
    for r in rows:
        through = r["data_through"]
        lag = (as_of - through).days if through else None
        if lag is None:
            st = '<span class="status old"><i></i>no dated rows</span>'
        elif lag <= 2:
            st = f'<span class="status fresh"><i></i>fresh ({lag} d)</span>'
        elif lag <= 7:
            st = f'<span class="status stale"><i></i>stale ({lag} d)</span>'
        else:
            st = f'<span class="status old"><i></i>old ({lag} d)</span>'
        loaded = (
            r["last_loaded_at"].strftime("%Y-%m-%d %H:%M") + " UTC" if r["last_loaded_at"] else "–"
        )
        row = [
            SOURCE_LABELS.get(r["source"], r["source"]),
            str(through or "–"),
            st,
            loaded,
            fmt_int(r["rows_loaded"]),
        ]
        if not app_id:
            row.insert(0, names.get(r["app_id"], r["app_id"]))
        out.append(row)
    header = ["Source", "Data through", "Freshness", "Last load", "Rows (last load)"]
    if not app_id:
        header.insert(0, "App")
    status_col = 3 if not app_id else 2
    return data_table(
        header, out, raw_html_cols=(status_col,), left_cols=(0, 1) if not app_id else (0,)
    )


def _series_by_date(rows: list[dict[str, Any]], key: str) -> list[Any]:
    return [r.get(key) for r in rows]


def _rolling(values: list[Any], window: int) -> list[float | None]:
    out: list[float | None] = []
    for i in range(len(values)):
        chunk = [v for v in values[max(0, i - window + 1) : i + 1] if v is not None]
        out.append(sum(chunk) / len(chunk) if len(chunk) == min(window, i + 1) and chunk else None)
    return out


