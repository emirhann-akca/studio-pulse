def portfolio_page(con, cfg, apps, alerts, rules, demo, as_of, checks=None) -> str:
    names = {a["app_id"]: a["name"] for a in apps}
    tot_dau = sum(a["dau_7d"] or 0 for a in apps)
    prev_dau = sum(a["dau_prev_7d"] or 0 for a in apps)
    rev = sum(a["revenue_7d_usd"] or 0 for a in apps)
    prev_rev = sum(a["revenue_prev_7d_usd"] or 0 for a in apps)
    new = sum(a["new_users_7d"] or 0 for a in apps)
    d1, t1 = _delta(tot_dau, prev_dau)
    d2, t2 = _delta(rev, prev_rev)
    crit = sum(1 for a in alerts if a.severity == "critical")
    tiles = [
        tile("Apps", str(len(apps))),
        tile("Portfolio DAU (7-day avg)", fmt_compact(tot_dau), d1, t1),
        tile("New users (7 days)", fmt_compact(new)),
        tile("Net revenue (7 days)", fmt_usd(rev), d2, t2, "IAP proceeds + ad earnings, USD"),
        tile(
            "Active alerts",
            str(len(alerts)),
            f"{crit} critical" if alerts else None,
            "bad" if crit else None,
        ),
    ]
    header = [
        "App",
        "Genre",
        "DAU 7d",
        "Δ DAU",
        "MAU",
        "DAU/MAU",
        "D1",
        "D7",
        "D30",
        "Revenue 7d",
        "ARPDAU",
        "Crash-free users",
        "Low-tier p50",
        "Rating",
    ]
    rows = []
    for a in apps:
        link = f'<a href="apps/{a["app_id"]}.html">{escape(a["name"])}</a>'
        rows.append(
            [
                link,
                escape(a["genre"] or ""),
                fmt_int(a["dau_7d"]),
                fmt_pct(a["dau_change"]) if a["dau_change"] is not None else "–",
                fmt_int(a["mau"]),
                fmt_pct(a["stickiness"]),
                fmt_pct(a["d1_retention"]),
                fmt_pct(a["d7_retention"]),
                fmt_pct(a["d30_retention"]),
                fmt_usd(a["revenue_7d_usd"]),
                fmt_usd(a["arpdau_7d"]),
                fmt_pct2(a["crash_free_users_7d"]),
                fmt_ms(a["low_tier_ft_p50_ms"]),
                f"{a['rating']:.2f}" if a["rating"] is not None else "–",
            ]
        )
    table = data_table(header, rows, raw_html_cols=(0,), left_cols=(0, 1))
    table += f'<p class="note" style="margin-top:8px">Mobile game benchmarks (all genres, GameAnalytics 2026): {escape(benchmarks.summary_text())}.</p>'
    daily = q(
        con,
        "SELECT app_id, date, dau, revenue_usd FROM fct_app_daily WHERE dau IS NOT NULL ORDER BY date",
    )
    dates = sorted({r["date"] for r in daily})
    idx = {d: i for i, d in enumerate(dates)}
    dau_series, rev_series = [], []
    for slot, a in enumerate(apps, start=1):
        dv, rv = [None] * len(dates), [None] * len(dates)
        for r in daily:
            if r["app_id"] == a["app_id"]:
                dv[idx[r["date"]]] = r["dau"]
                rv[idx[r["date"]]] = r["revenue_usd"]
        dau_series.append(Series(a["name"], dv, slot=min(slot, 8)))
        rev_series.append(Series(a["name"], rv, slot=min(slot, 8)))
    rev_series = [Series(s.name, _rolling(s.values, 7), slot=s.slot) for s in rev_series]
    charts = (
        '<div class="grid2">'
        + line_chart(
            "Daily active users by app",
            dates,
            dau_series,
            fmt_compact,
            "Distinct users with at least one non-passive event per day",
        )
        + line_chart(
            "Net revenue by app (7-day average)",
            dates,
            rev_series,
            fmt_usd,
            "IAP proceeds + ad earnings per day, USD, trailing 7-day mean",
        )
        + "</div>"
    )
    body = (
        f'<div class="tiles">{"".join(tiles)}</div>'
        f"<h2>Apps</h2>{table}"
        f"<h2>Trends</h2>{charts}"
        f"<h2>Alerts</h2>{_alerts_html(alerts, names, rules)}"
        f"<h2>Data quality</h2>{_checks_html(checks)}"
        f"<h2>Data freshness</h2>{_freshness(con, as_of, None, names)}"
    )
    return _page(cfg, cfg.title, body, apps, None, demo, as_of, "")


